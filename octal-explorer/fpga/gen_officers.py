#!/usr/bin/env python3
"""Generate the Officers (.6) speculation core for an FPGA (Grossman 2017, section 4).

Grossman, "Searching for periodicity in Officers" (GONC 5), ends with the idea
of putting "the unrolled single-threaded algorithm directly in hardware using a
FPGA ... a new value on every clock cycle".  This script writes that core as
SystemVerilog: the *speculative* step 1 of the rare-value algorithm
(Figure 3 / section 3.1), which assumes that no new rare value appears.  The
values it streams out must still be checked (step 2) on the host, exactly as
for the CPU speculation in octal.c (rare_spec_run()).

Officers: G(n) = mex{ G(n-1) } u { G(a) ^ G(n-1-a) : 1 <= a <= n-2 }.
A value v is rare iff popcount(v & 0x1EE) is even (bits 1,2,3,5,6,7,8).  With
the 1584 rare heap sizes R = {0, 1, 2, 4, ...,20627} (all below 20628),
step 1 is

    M(n)  = { G(a) ^ G(n-1-a) : a in R }     (a = 0 is the one-heap move)
    G(n) ~= smallest common value not in M(n)

and only common marks matter (rare ^ common = common, rare ^ rare = rare).

Hardware (one G(n) per clock, see docs/fpga.md):

* history H[j] = G(n-1-j), a shift register 9 bits wide; each entry stores
  {common flag, low 8 bits}.  A common value is determined by its low 8 bits
  (bit 8 is fixed by the parity), so the 256 common values below 512 are the
  256 mask positions.  Mask position p is the p-th smallest common value.
* every rare heap a >= 1 is a tap.  Its value is predecoded once into 16 + 16
  nibble lines, and mask bit p of the term is hi[x] & lo[y] for the constant
  (x, y) = nibbles of low8(cv[p] ^ G(a)).
* a pipelined OR tree (T register stages) builds the mask of all terms a >= T
  for heap size n + 1 from tap H[a - T]; the few rare a in [1, T) are ORed into
  its last stage from H[a - 1].  Its last stage is the register M0 = M(n+1)
  without the a = 0 term.
* the only loop is  H0 -> onehot -> (| M0) -> find first zero -> H0:
  G(n) = first free common value of M0 | {G(n-1)}.

Every register sits behind one clock enable (a load or a computed value), so
the pipeline stays consistent with the history through stalls and the preload.

Usage:
    gen_officers.py [--values FILE | --octal PATH] [--tree-group N] [-o DIR]

Writes officers_core.sv and officers_params.json (rare table, tap layout,
preload length) to DIR.
"""
import argparse
import json
import os
import re
import subprocess
import sys

MASK = 0x1EE          # Grossman: bits 1, 2, 3, 5, 6, 7, 8
NVAL = 512            # all known Officers values are below 512 (max 388)


def parity(x):
    return bin(x).count("1") & 1


def is_rare(v):
    return parity(v & MASK) == 0


def common_values():
    """The 256 common values below 512, ascending; position p <-> cv[p]."""
    cv = [v for v in range(NVAL) if not is_rare(v)]
    assert len(cv) == 256
    # a common value is determined by its low 8 bits
    assert len({v & 0xFF for v in cv}) == 256
    return cv


def load_values(args):
    if args.values:
        text = open(args.values).read()
    else:
        text = subprocess.run([args.octal, ".6", "-n", str(args.n), "-p", "--rare", "-q"],
                              check=True, capture_output=True, text=True).stdout
    return [int(t) for t in re.findall(r"\d+", text)]


def emit(out, rare, G, T, group):
    """Write the SystemVerilog core.  rare: rare heap sizes >= 1 (sorted)."""
    cv = common_values()
    taps_tree = [a for a in rare if a >= T]           # tree terms, tap H[a - T]
    taps_late = [a for a in rare if a < T]            # last-stage terms, tap H[a - 1]
    depth = max(rare) - T + 1 if taps_tree else T     # history entries H[0 .. depth-1]
    depth = max(depth, max(taps_late, default=1))

    L = []
    w = L.append
    w("// Generated by fpga/gen_officers.py -- do not edit.")
    w("// Officers (.6) speculation core: Grossman 2017, Figure 3 in hardware.")
    w(f"// {len(rare) + 1} rare heap sizes (incl. 0), largest {max(rare)}; mask 0x{MASK:03x}.")
    w(f"// OR tree: {T} register stages, first-level groups of {group} terms.")
    w("`default_nettype none")
    w("module officers_core (")
    w("    input  wire       clk,")
    w("    input  wire       rst,        // clears out_valid / err only")
    w("    input  wire       load,       // shift load_data into the history")
    w("    input  wire [8:0] load_data,  // G(n0 - PRELOAD + i), i = 0 .. PRELOAD-1")
    w("    input  wire       run,        // compute the next value (ignored while load)")
    w("    output reg        out_valid,")
    w("    output reg  [8:0] out_data,   // speculative G(n0), G(n0+1), ...")
    w("    output reg        err         // sticky: all 256 common values were marked")
    w(");")
    w(f"localparam int DEPTH = {depth};")
    w(f"localparam int PRELOAD = {depth + T + 1};")
    w("wire ce = load | run;")
    lows = ", ".join("8'd%d" % (v & 0xFF) for v in cv)
    w(f"// mask position p <-> p-th smallest common value cv[p] = {{CV_B8[p], CV_LOW[p]}}")
    w(f"localparam logic [7:0] CV_LOW [0:255] = '{{{lows}}};")
    b8 = int("".join(str(cv[p] >> 8) for p in reversed(range(256))), 2)
    w(f"localparam logic [255:0] CV_B8 = 256'h{b8:064x};")
    w("")
    w("// ---- history: H[j] = {common, low8} of G(n-1-j) ----")
    w("reg [8:0] H [0:DEPTH-1];")
    w("wire [8:0] g_new;          // {common, low8} of the computed value")
    w("wire [8:0] load_enc = {^(load_data & 9'h1EE), load_data[7:0]};  // odd parity = common")
    w("always @(posedge clk) if (ce) begin")
    w("    H[0] <= load ? load_enc : g_new;")
    w("    for (int j = 1; j < DEPTH; j++) H[j] <= H[j-1];")
    w("end")
    w("")

    # predecode per tap
    def predecode(name, idx):
        w(f"wire [15:0] {name}_hi = H[{idx}][8] ? (16'd1 << H[{idx}][7:4]) : 16'd0;")
        w(f"wire [15:0] {name}_lo = 16'd1 << H[{idx}][3:0];")

    def term_bit(name, r, p):
        l = (cv[p] ^ r) & 0xFF
        return f"{name}_hi[{l >> 4}] & {name}_lo[{l & 15}]"

    w("// ---- tree terms: rare heap a >= T, tap H[a - T] ----")
    for i, a in enumerate(taps_tree):
        w(f"// a = {a}, G(a) = {G[a]}")
        predecode(f"t{i}", a - T)
    w("")

    # first level: groups of `group` terms, registered
    ngroups = (len(taps_tree) + group - 1) // group
    w("// ---- OR tree level 1 ----")
    w(f"reg [255:0] L1 [0:{max(ngroups,1)-1}];")
    w("always @(posedge clk) if (ce) begin")
    for g in range(ngroups):
        members = list(range(g * group, min((g + 1) * group, len(taps_tree))))
        for p in range(256):
            terms = " | ".join(f"({term_bit(f't{i}', G[taps_tree[i]], p)})" for i in members)
            w(f"    L1[{g}][{p}] <= {terms};")
    w("end")
    cur, cnt, lev = "L1", ngroups, 1
    fan = 1
    while fan ** (T - 1) < cnt:       # fan-in per stage for the T-1 stages after L1
        fan += 1
    for _ in range(T - 2):            # middle stages; M0 takes the rest
        nn = -(-cnt // fan)
        lev += 1
        nxt = f"L{lev}"
        w(f"reg [255:0] {nxt} [0:{nn-1}];")
        w("always @(posedge clk) if (ce) begin")
        for g in range(nn):
            mem = " | ".join(f"{cur}[{i}]" for i in range(g * fan, min((g + 1) * fan, cnt)))
            w(f"    {nxt}[{g}] <= {mem};")
        w("end")
        cur, cnt = nxt, nn
    w("")
    w("// ---- last stage M0: tree | rare a in [1, T) from H[a - 1] ----")
    for i, a in enumerate(taps_late):
        w(f"// a = {a}, G(a) = {G[a]}")
        predecode(f"e{i}", a - 1)
    w("reg [255:0] M0;")
    w("always @(posedge clk) if (ce) begin")
    for p in range(256):
        parts = [f"{cur}[{i}][{p}]" for i in range(cnt)]
        parts += [f"({term_bit(f'e{i}', G[a], p)})" for i, a in enumerate(taps_late)]
        w(f"    M0[{p}] <= {' | '.join(parts) if parts else "1'b0"};")
    w("end")
    w("")
    w("// ---- the loop: G(n) = first free common value of M0 | {G(n-1)} ----")
    w("wire [255:0] own;   // a = 0: the one-heap move, value G(n-1)")
    w("genvar p;")
    w("generate for (p = 0; p < 256; p++) begin : g_own")
    w("    assign own[p] = H[0][8] & (H[0][7:0] == CV_LOW[p]);")
    w("end endgenerate")
    w("wire [255:0] free_ = ~(M0 | own);")
    w("wire [7:0] first;   // position of the lowest set bit of free_")
    w("wire       any;")
    w("ffs256 u_ffs (.x(free_), .idx(first), .any(any));")
    w("assign g_new = {1'b1, CV_LOW[first]};")
    w("always @(posedge clk) begin")
    w("    if (rst) begin out_valid <= 1'b0; err <= 1'b0; end")
    w("    else begin")
    w("        out_valid <= run & ~load;")
    w("        if (run & ~load & ~any) err <= 1'b1;")
    w("    end")
    w("    out_data <= {CV_B8[first], CV_LOW[first]};")
    w("end")
    w("endmodule")
    w("")
    # find-first-set: radix-4 tree, emitted level by level
    w("// lowest set bit of a 256-bit vector, radix-4 tree")
    w("module ffs256 (input wire [255:0] x, output wire [7:0] idx, output wire any);")
    w("    wire [255:0] v0 = x;")
    n, width = 256, 0
    for lv in range(4):
        m = n // 4
        w(f"    wire [{m-1}:0] v{lv+1};")
        if width:
            w(f"    wire [{m*(width+2)-1}:0] i{lv+1};")
        else:
            w(f"    wire [{m*2-1}:0] i{lv+1};")
        w(f"    genvar g{lv};")
        w(f"    generate for (g{lv} = 0; g{lv} < {m}; g{lv}++) begin : l{lv}")
        w(f"        wire [3:0] q = v{lv}[4*g{lv} +: 4];")
        w(f"        wire [1:0] s = q[0] ? 2'd0 : q[1] ? 2'd1 : q[2] ? 2'd2 : 2'd3;")
        w(f"        assign v{lv+1}[g{lv}] = |q;")
        if width:
            W = width
            w(f"        wire [{W-1}:0] sub = s == 2'd0 ? i{lv}[{W}*(4*g{lv}+0) +: {W}] :")
            w(f"                         s == 2'd1 ? i{lv}[{W}*(4*g{lv}+1) +: {W}] :")
            w(f"                         s == 2'd2 ? i{lv}[{W}*(4*g{lv}+2) +: {W}] :")
            w(f"                                     i{lv}[{W}*(4*g{lv}+3) +: {W}];")
            w(f"        assign i{lv+1}[{W+2}*g{lv} +: {W+2}] = {{s, sub}};")
        else:
            w(f"        assign i{lv+1}[2*g{lv} +: 2] = s;")
        w("    end endgenerate")
        n, width = m, width + 2
    w("    assign idx = i4[7:0];")
    w("    assign any = v4[0];")
    w("endmodule")
    w("`default_nettype wire")
    out.write("\n".join(L) + "\n")
    return depth


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--values", help="text file with G(0), G(1), ... (octal -p output)")
    ap.add_argument("--octal", default=os.path.join(os.path.dirname(__file__), "..", "octal"),
                    help="octal binary used when --values is not given")
    ap.add_argument("-n", type=int, default=100000, help="values to compute with octal (default 1e5)")
    ap.add_argument("--tree-stages", type=int, default=3, help="OR tree register stages incl. M0 (>= 2)")
    ap.add_argument("--tree-group", type=int, default=18, help="terms per first-level group")
    ap.add_argument("-o", default=os.path.join(os.path.dirname(__file__), "build"), help="output directory")
    args = ap.parse_args()
    if args.tree_stages < 2:
        sys.exit("--tree-stages must be >= 2")

    G = load_values(args)
    rare = [a for a in range(1, len(G)) if is_rare(G[a])]
    if max(rare) * 4 > len(G):
        print(f"warning: last rare heap {max(rare)} is not far below n = {len(G)}", file=sys.stderr)
    os.makedirs(args.o, exist_ok=True)
    with open(os.path.join(args.o, "officers_core.sv"), "w") as f:
        depth = emit(f, rare, G, args.tree_stages, args.tree_group)
    T = args.tree_stages
    params = {"mask": MASK, "rare": [0] + rare, "rare_values": [G[0]] + [G[a] for a in rare],
              "tree_stages": T, "tree_group": args.tree_group, "depth": depth,
              "preload": depth + T + 1, "min_n0": max(max(rare) + 2, depth + T + 1)}
    with open(os.path.join(args.o, "officers_params.json"), "w") as f:
        json.dump(params, f)
    print(f"{len(rare) + 1} rare heap sizes, history depth {depth}, preload {params['preload']}, "
          f"tree {T} stages -> {args.o}/officers_core.sv")


if __name__ == "__main__":
    main()
