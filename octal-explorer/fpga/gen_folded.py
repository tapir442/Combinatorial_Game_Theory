#!/usr/bin/env python3
"""Generate the *folded* Officers speculation core: one G(n) every P clocks.

The full core (gen_officers.py) evaluates all 1583 rare taps in one clock and
needs about 265k LUTs.  This one evaluates S = ceil(1583 / P) taps per clock,
using S *slots*.  Each slot reads one of P history taps per clock, chosen by
the window phase, and XORs that tap's rare value G(a) into it before decoding.
Then every slot has the same 256-bit decode (no per-tap constants), and the
OR tree is shared by all P phases.  With P = 8 it fits an Artix-7 100T.

Timing, with H[j] = G(m-1-j) after the shift that ends period m-1:

* window W_m = phase 2 of period m .. phase 1 of period m+1, where H[j] = G(m-j).
  Window phase w = (ph - 2) mod P feeds tap set w of every slot.  Heap m+2 needs
  G(m+1-a) = H[a-1] for each rare a >= 1.
* D = 5 register stages (slot mux, nibble predecode, 3-slot AND-OR, 6-way OR,
  6-way OR), one LUT level each; then the accumulator ORs the P phases.  The
  last phase, issued at phase 1 of period m+1, reaches it at phase 1 + D = 6
  and writes RES = all a >= 1 terms | the a = 0 term onehot(G(m+1)) (H[0] since
  that shift).
* F = 3 clocks of first-free search on RES: 16-bit chunks (phase 7), across the
  chunks (phase 0), value lookup at phase 1 of period m+2, where G(m+2) is
  shifted into H.  So P >= D + F = 8.

History dump: the oldest entry comes out as `tail`.  Fast-loading it back
(ld_fast_d with ld_data = its decoded value) DEPTH times rotates the history once
around; the engine is frozen meanwhile, so the core continues as before.

Stalls: the data path runs every clock.  A window phase is *valid* only in the
clock in which the phase counter moves on (ce); repeats issued while stalled
are ignored by the accumulator.  The only enables with a large fan-out are the
history shift (registered, computed one clock ahead from ce_d / ld_fast_d) and
the accumulator's valid flags.

    gen_folded.py [--values FILE] [--fold P] [-o DIR]
writes DIR/officers_folded.sv, DIR/folded_info.svh and DIR/folded_params.json.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_officers import MASK, common_values, is_rare  # noqa: E402

D = 5          # register stages from the slot mux to the accumulator input
F = 3          # clocks of first-free search (the last one feeds the history)


def emit(out, rare, G, P):
    cv = common_values()
    terms = [(a, G[a]) for a in rare]                  # a >= 1
    S = -(-len(terms) // P)
    depth = max(rare)                                   # H[0 .. max(a) - 1]
    # term i -> slot i % S, phase i // S
    tap = [[-1] * P for _ in range(S)]
    rlo = [[0] * P for _ in range(S)]
    for i, (a, r) in enumerate(terms):
        s, w = i % S, i // S
        tap[s][w] = a - 1
        rlo[s][w] = r & 0xFF
    NT = -(-S // 3)            # slot triples   (stage 3: one LUT6 per bit)
    NG = -(-NT // 6)           # triple groups  (stage 4)
    NH = -(-NG // 6)           # group halves   (stage 5)
    assert NH <= 3, "accumulator LUT needs at most 3 inputs from the tree"
    pw = max(1, (P - 1).bit_length())

    L = []
    w = L.append
    w("// Generated by fpga/gen_folded.py -- do not edit.")
    w(f"// Folded Officers (.6) speculation core: {len(terms)} rare taps (a >= 1) in {S} slots x {P} phases,")
    w(f"// one value every {P} clocks; {D} data stages + {F} first-free stages.  Rare mask 0x{MASK:03x}.")
    w("`default_nettype none")
    w("module officers_folded (")
    w("    input  wire       clk,")
    w("    input  wire       rst,       // clears err, out_valid, phase, enables")
    w("    input  wire       ce_d,      // the core advances in the NEXT clock")
    w("    input  wire       ld_fast_d, // the next clock shifts ld_data into the history (engine frozen; not with ce_d)")
    w("    input  wire       ld_slow,   // this clock: a shift takes ld_data instead of the computed value")
    w("    input  wire [8:0] ld_data,   // used in the clock of the shift")
    w("    output wire       shifting,  // this clock shifts a value into the history (advance at phase 1)")
    w("    output reg        out_valid, // one clock, after a computed value")
    w("    output reg  [8:0] out_data,")
    w("    output reg        err,       // sticky: all 256 common values marked")
    w("    output reg  [8:0] tail       // H[DEPTH-1] (encoded) one clock late: for dumping the history")
    w(");")
    w(f"localparam int P = {P};")
    w(f"localparam int S = {S};")
    w(f"localparam int DEPTH = {depth};")
    lows = ", ".join("8'd%d" % (v & 0xFF) for v in cv)
    w(f"localparam logic [7:0] CV_LOW [0:255] = '{{{lows}}};")
    b8 = int("".join(str(cv[p] >> 8) for p in reversed(range(256))), 2)
    w(f"localparam logic [255:0] CV_B8 = 256'h{b8:064x};")
    w("")
    w("// ---- control: registered enables, computed one clock ahead ----")
    w("reg ce_q = 1'b0, ldf_q = 1'b0;")
    w("(* max_fanout = 200 *) reg shf_q = 1'b0;          // history shift in this clock")
    w(f"reg [{pw-1}:0] ph = 0;")
    w(f"(* max_fanout = 40 *) reg [{pw-1}:0] wph = {pw}'(P-2);   // window phase (ph - 2) mod P")
    w("assign shifting = ce_q & (ph == 1);")
    w(f"wire [{pw-1}:0] ph_n = ce_q ? ((ph == P-1) ? {pw}'d0 : ph + 1'b1) : ph;")
    w("always @(posedge clk) begin")
    w("    if (rst) begin")
    w(f"        ce_q <= 1'b0; ldf_q <= 1'b0; shf_q <= 1'b0; ph <= 0; wph <= {pw}'(P-2);")
    w("    end else begin")
    w("        ce_q  <= ce_d;")
    w("        ldf_q <= ld_fast_d;")
    w("        shf_q <= ld_fast_d | (ce_d & (ph_n == 1));")
    w("        ph    <= ph_n;")
    w(f"        if (ce_q) wph <= (wph == P-1) ? {pw}'d0 : wph + 1'b1;")
    w("    end")
    w("end")
    w("")
    w("// ---- history H[j] = {common, low8} ----")
    w("reg  [8:0] H [0:DEPTH-1];")
    w("wire [8:0] g_enc;")
    w("wire [8:0] ld_enc = {^(ld_data & 9'h1EE), ld_data[7:0]};   // odd parity = common")
    w("always @(posedge clk) if (shf_q) begin")
    w("    H[0] <= (ldf_q | ld_slow) ? ld_enc : g_enc;")
    w("    for (int j = 1; j < DEPTH; j++) H[j] <= H[j-1];")
    w("end")
    w("always @(posedge clk) tail <= H[DEPTH-1];")
    w("")
    w("// ---- stage 1: slot muxes (tap by window phase) and XOR with G(a); valid/first/last tags ----")
    w("reg [8:0] v1 [0:S-1];")
    w("reg [5:1] vv, ff, ll;          // tags per stage: valid, first phase, last phase")
    w("always @(posedge clk) begin")
    w("    vv[1] <= ce_q & ~rst;")
    w("    ff[1] <= (wph == 0);")
    w("    ll[1] <= (wph == P-1);")
    w("    for (int k = 2; k <= 5; k++) begin vv[k] <= vv[k-1]; ff[k] <= ff[k-1]; ll[k] <= ll[k-1]; end")
    w("    case (wph)")
    for ph in range(P):
        w(f"    {ph}: begin")
        for s in range(S):
            t = tap[s][ph]
            if t < 0:
                w(f"        v1[{s}] <= 9'd0;")
            else:
                w(f"        v1[{s}] <= {{H[{t}][8], H[{t}][7:0] ^ 8'd{rlo[s][ph]}}};")
        w("    end")
    w("    default: ;")
    w("    endcase")
    w("end")
    w("")
    w("// ---- stage 2: nibble predecode (the common flag gates hi) ----")
    w("reg [15:0] hi2 [0:S-1];")
    w("reg [15:0] lo2 [0:S-1];")
    w("always @(posedge clk)")
    w("    for (int s = 0; s < S; s++) begin")
    w("        hi2[s] <= v1[s][8] ? (16'd1 << v1[s][7:4]) : 16'd0;")
    w("        lo2[s] <= 16'd1 << v1[s][3:0];")
    w("    end")
    w("")
    w(f"// ---- stage 3: {NT} slot triples, bit p = OR of hi[x_p] & lo[y_p] (one LUT6) ----")
    w(f"reg [255:0] t3 [0:{NT-1}];")
    w("always @(posedge clk)")
    w(f"    for (int j = 0; j < {NT}; j++)")
    w("        for (int p = 0; p < 256; p++) begin")
    w("            logic b;")
    w("            b = 1'b0;")
    w("            for (int k = 0; k < 3; k++)")
    w("                if (3*j + k < S) b = b | (hi2[3*j+k][CV_LOW[p][7:4]] & lo2[3*j+k][CV_LOW[p][3:0]]);")
    w("            t3[j][p] <= b;")
    w("        end")
    w("")
    w(f"// ---- stage 4: {NG} groups of up to 6 triples ----")
    w(f"reg [255:0] t4 [0:{NG-1}];")
    w("always @(posedge clk)")
    w(f"    for (int g = 0; g < {NG}; g++) begin")
    w("        logic [255:0] b;")
    w("        b = '0;")
    w(f"        for (int k = 0; k < 6; k++) if (6*g + k < {NT}) b = b | t3[6*g+k];")
    w("        t4[g] <= b;")
    w("    end")
    w("")
    w(f"// ---- stage 5: {NH} terms of up to 6 groups ----")
    w(f"reg [255:0] t5 [0:{NH-1}];")
    w("always @(posedge clk)")
    w(f"    for (int h = 0; h < {NH}; h++) begin")
    w("        logic [255:0] b;")
    w("        b = '0;")
    w(f"        for (int k = 0; k < 6; k++) if (6*h + k < {NG}) b = b | t4[6*h+k];")
    w("        t5[h] <= b;")
    w("    end")
    w("")
    w("// ---- a = 0 term: onehot of H[0] (two stages; ready 2 clocks after a shift) ----")
    w("reg [15:0] oh_hi, oh_lo;")
    w("reg [255:0] own;")
    w("always @(posedge clk) begin")
    w("    oh_hi <= H[0][8] ? (16'd1 << H[0][7:4]) : 16'd0;")
    w("    oh_lo <= 16'd1 << H[0][3:0];")
    w("    for (int p = 0; p < 256; p++) own[p] <= oh_hi[CV_LOW[p][7:4]] & oh_lo[CV_LOW[p][3:0]];")
    w("end")
    w("")
    w("// ---- accumulate the valid phases of a window; the last one writes RES ----")
    tsum = " | ".join(f"t5[{h}]" for h in range(NH))
    w(f"wire [255:0] T = {tsum};")
    w("reg [255:0] ACC, RES;")
    w("always @(posedge clk) if (vv[5]) begin")
    w("    ACC <= ff[5] ? T : (ACC | T);")
    w("    if (ll[5]) RES <= ACC | T | own;")
    w("end")
    w("")
    w("// ---- first free common value of RES: chunks, across chunks, lookup ----")
    w("function automatic [3:0] first16(input [15:0] x);")
    w("    first16 = 4'd0;")
    w("    for (int i = 15; i >= 0; i--) if (x[i]) first16 = i[3:0];")
    w("endfunction")
    w("reg [15:0] c_any;")
    w("reg [3:0]  c_idx [0:15];")
    w("always @(posedge clk)")
    w("    for (int c = 0; c < 16; c++) begin")
    w("        c_any[c] <= ~&RES[16*c +: 16];")
    w("        c_idx[c] <= first16(~RES[16*c +: 16]);")
    w("    end")
    w("reg [7:0] pos;")
    w("reg       any;")
    w("always @(posedge clk) begin")
    w("    logic [3:0] fc;")
    w("    fc = first16(c_any);")
    w("    any <= |c_any;")
    w("    pos <= {fc, c_idx[fc]};")
    w("end")
    w("assign g_enc = {1'b1, CV_LOW[pos]};")
    w("always @(posedge clk) begin")
    w("    if (rst) begin out_valid <= 1'b0; err <= 1'b0; end")
    w("    else begin")
    w("        out_valid <= shifting & ~ld_slow;")
    w("        if (shifting & ~ld_slow & ~any) err <= 1'b1;")
    w("    end")
    w("    if (shifting) out_data <= {CV_B8[pos], CV_LOW[pos]};")
    w("end")
    w("endmodule")
    w("`default_nettype wire")
    out.write("\n".join(L) + "\n")
    return S, depth


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--values", required=True, help="text file with G(0), G(1), ... (octal -p output)")
    ap.add_argument("--fold", "-P", type=int, default=8, help=f"clocks per value (>= {D + F})")
    ap.add_argument("-o", default=os.path.join(os.path.dirname(__file__), "build"))
    args = ap.parse_args()
    if args.fold < D + F:
        sys.exit(f"--fold must be >= {D + F}")
    G = [int(t) for t in re.findall(r"\d+", open(args.values).read())]
    rare = [a for a in range(1, len(G)) if is_rare(G[a])]
    os.makedirs(args.o, exist_ok=True)
    with open(os.path.join(args.o, "officers_folded.sv"), "w") as f:
        S, depth = emit(f, rare, G, args.fold)
    params = {"mask": MASK, "rare": [0] + rare, "rare_values": [G[0]] + [G[a] for a in rare],
              "fold": args.fold, "slots": S, "depth": depth,
              # fast-load everything but the last two values, which go through
              # periods so that RES for the first computed heap is built
              "preload": depth + 2, "slow": 2, "min_n0": max(rare) + 2}
    with open(os.path.join(args.o, "folded_info.svh"), "w") as f:
        f.write("// Generated by fpga/gen_folded.py\n"
                f"`define FOLD_P {args.fold}\n`define FOLD_S {S}\n`define FOLD_DEPTH {depth}\n")
    with open(os.path.join(args.o, "folded_params.json"), "w") as f:
        json.dump(params, f)
    print(f"{len(rare)} taps -> {S} slots x {args.fold} phases, history {depth} -> {args.o}/officers_folded.sv")


if __name__ == "__main__":
    main()
